BEGIN TRY
    BEGIN TRANSACTION;

    /* ---------------- ПРИЛАГАНЕ ---------------- */

    -- 1) Липсващите услуги се създават; всички от списъка са активни.
    INSERT INTO dbo.Services (Name, Description, IsActive)
    SELECT DISTINCT t.Name, NULL, 1
    FROM @T t
    WHERE NOT EXISTS (SELECT 1 FROM dbo.Services s WHERE s.Name = t.Name);

    UPDATE s SET IsActive = 1
    FROM dbo.Services s
    WHERE s.Name IN (SELECT Name FROM @T);

    -- 2) Услугите, които ги няма в Studio 24, стават неактивни.
    UPDATE dbo.Services SET IsActive = 0
    WHERE Name NOT IN (SELECT Name FROM @T);

    -- 3) Махат се връзките, които не са в списъка
    --    (стари услуги или грешна специалистка).
    DELETE es
    FROM dbo.EmployeeServices es
    JOIN dbo.Services s ON s.Id = es.ServiceId
    WHERE NOT EXISTS (SELECT 1 FROM @T t WHERE t.Name = s.Name AND t.EmployeeId = es.EmployeeId);

    -- 4) Цена и времетраене: обновяване на съществуващите…
    UPDATE es SET Price = t.Price, DurationMinutes = t.DurationMinutes
    FROM dbo.EmployeeServices es
    JOIN dbo.Services s ON s.Id = es.ServiceId
    JOIN @T t ON t.Name = s.Name AND t.EmployeeId = es.EmployeeId;

    --    …и добавяне на липсващите.
    INSERT INTO dbo.EmployeeServices (EmployeeId, ServiceId, Price, DurationMinutes)
    SELECT t.EmployeeId, s.Id, t.Price, t.DurationMinutes
    FROM @T t
    JOIN dbo.Services s ON s.Name = t.Name
    WHERE NOT EXISTS (SELECT 1 FROM dbo.EmployeeServices es WHERE es.ServiceId = s.Id AND es.EmployeeId = t.EmployeeId);

    COMMIT TRANSACTION;
    PRINT N'Готово: услугите и цените съвпадат със Studio 24.';
END TRY
